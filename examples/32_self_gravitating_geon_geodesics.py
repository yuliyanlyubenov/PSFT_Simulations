# ---------------------------------------------------------------------------
# Metric wrapper: extract a 4-metric at any spacetime point from a BSSN
# state by trilinear interpolation.  Assumes conformally-flat IC
# (gammabar_ij = delta_ij), K_ij = 0 (time-symmetric slice), so the
# 4-metric is static and diagonal:
#     g_tt = -alpha^2,   g_ij = (1/chi) delta_ij.
# ---------------------------------------------------------------------------
class BSSNGriddedMetric(Metric):
    name = "bssn_gridded"

    def __init__(self, bssn_state: BSSNState, L: float):
        self.bssn = bssn_state
        self.L = L
        self.dx = bssn_state.dx
        self.dy = bssn_state.dy
        self.dz = bssn_state.dz
        Nx, Ny, Nz = bssn_state.chi.shape
        self.Nx, self.Ny, self.Nz = Nx, Ny, Nz
        # Cell-centred coordinates (matching the BSSN convention).
        # Box spans [0, L]; cell centres at 0.5*dx ... L - 0.5*dx.

    def _trilinear(self, F: np.ndarray, x: float, y: float, z: float) -> float:
        """Trilinear interpolation of 3D array F at spatial point (x, y, z).
        Periodic BCs to match the underlying BSSN grid."""
        ix = (x - 0.5 * self.dx) / self.dx
        iy = (y - 0.5 * self.dy) / self.dy
        iz = (z - 0.5 * self.dz) / self.dz
        i0 = int(np.floor(ix)) % self.Nx
        j0 = int(np.floor(iy)) % self.Ny
        k0 = int(np.floor(iz)) % self.Nz
        i1 = (i0 + 1) % self.Nx
        j1 = (j0 + 1) % self.Ny
        k1 = (k0 + 1) % self.Nz
        fx = ix - np.floor(ix)
        fy = iy - np.floor(iy)
        fz = iz - np.floor(iz)
        c00 = F[i0, j0, k0] * (1 - fx) + F[i1, j0, k0] * fx
        c01 = F[i0, j0, k1] * (1 - fx) + F[i1, j0, k1] * fx
        c10 = F[i0, j1, k0] * (1 - fx) + F[i1, j1, k0] * fx
        c11 = F[i0, j1, k1] * (1 - fx) + F[i1, j1, k1] * fx
        c0 = c00 * (1 - fy) + c10 * fy
        c1 = c01 * (1 - fy) + c11 * fy
        return float(c0 * (1 - fz) + c1 * fz)

    def g(self, x):
        # Static metric -- ignores x[0] (time).
        chi = self._trilinear(self.bssn.chi, x[1], x[2], x[3])
        alpha = self._trilinear(self.bssn.alpha, x[1], x[2], x[3])
        chi_safe = max(chi, 1e-12)
        out = np.zeros((4, 4))
        out[0, 0] = -alpha * alpha
        out[1, 1] = 1.0 / chi_safe
        out[2, 2] = 1.0 / chi_safe
        out[3, 3] = 1.0 / chi_safe
        return out

    def dg(self, x, h=None):
        """Finite-difference derivatives of g.  Override the abstract
        default (which uses h = 1e-5 -- much smaller than our grid
        spacing); use h = grid spacing instead so the interpolation
        actually samples adjacent cells."""
        if h is None:
            h = max(self.dx, self.dy, self.dz)
        out = np.zeros((4, 4, 4))
        for c in range(4):
            xp = x.copy(); xp[c] += h
            xm = x.copy(); xm[c] -= h
            out[c] = (self.g(xp) - self.g(xm)) / (2 * h)
        return out


def null_initial_velocity(metric: Metric, x: np.ndarray, direction: np.ndarray):
    """Build a null 4-velocity at x propagating in spatial `direction`.

    For a diagonal metric g_tt = -alpha^2, g_ij = (1/chi) delta_ij:
    require -alpha^2 (u^t)^2 + (1/chi) |u_spatial|^2 = 0
    => u^t = sqrt(|u_spatial|^2 / chi) / alpha.
    We choose |u_spatial| = 1 (unit spatial direction).
    """
    g = metric.g(x)
    alpha = float(math.sqrt(-g[0, 0]))
    gamma_xx = float(g[1, 1])     # = 1/chi
    # |u_spatial|^2 with metric: gamma_xx * sum(direction[i]^2)  (diagonal)
    u_sp_norm = math.sqrt(gamma_xx * float(np.sum(direction ** 2)))
    u_t = u_sp_norm / alpha
    u = np.zeros(4)
    u[0] = u_t
    u[1:] = direction
    return u


def main():
    print("Example 32: trapped null geodesics on a self-gravitating "
          "NUMERICAL metric")
    print("(Wheeler-geon trapping with matter-sourced curvature, "
          "paper Section 7.4)")
    print("=" * 70)

    HIGH_RES = os.environ.get("PSFT_HIGH_RES", "0") != "0"
    N = 48 if HIGH_RES else 32
    L = 2.0
    dh = L / N

    print(f"  HIGH_RES = {HIGH_RES}")
    print(f"  grid: {N}^3, L = {L}, dh = {dh:.4f}")

    # Build a Gaussian dust distribution at MODERATE compactness.  We
    # stay in the regime where the Lichnerowicz-solved metric is
    # smooth enough that trilinear-interpolated finite-difference
    # Christoffel symbols are reliable.  The geometric strong-field
    # regime where light is fully captured by an event horizon requires
    # either a much finer grid + higher-order interpolation or the full
    # BSSN puncture treatment (deferred).  Here we demonstrate that the
    # CURVED-METRIC GEODESIC EQUATION on a NUMERICAL spatial geometry
    # produces visible photon deflection toward the matter -- the
    # leading-order Wheeler-geon focussing.  Full trapping with the
    # discontinuous-at-Kc^strong topology change of paper Section 7.4
    # is the natural follow-on, requiring the strong-field machinery
    # listed in the Open Problems section.
    x = np.linspace(0.5*dh, L-0.5*dh, N)
    X, Y, Z = np.meshgrid(x, x, x, indexing='ij')
    r = np.sqrt((X - L/2)**2 + (Y - L/2)**2 + (Z - L/2)**2)
    sigma = 0.25
    rho_amp = 0.05             # moderate-field source
    rho_rest = rho_amp * np.exp(-r**2 / (2 * sigma**2))
    M_int = float(np.sum(rho_rest)) * dh ** 3
    print(f"  Gaussian source: sigma = {sigma}, rho_amp = {rho_amp}, "
          f"M_int = {M_int:.3f}")
    print(f"  compactness M_int / sigma = {M_int / sigma:.3f}  "
          f"(moderate field; resolved by N^3 = {N}^3)")

    # Solve Lichnerowicz constraint.
    print()
    print("  Solving Lichnerowicz constraint ...")
    t_j = time.time()
    bssn, rho_adm = BSSNState.static_dust_ball(
        N, N, N, dh, dh, dh, rho_rest=rho_rest, n_jacobi=5000, tol=1e-9,
    )
    print(f"  Jacobi solve: {time.time() - t_j:.1f}s")
    print(f"    chi range:   [{bssn.chi.min():.4f}, {bssn.chi.max():.4f}]")
    print(f"    alpha range: [{bssn.alpha.min():.4f}, {bssn.alpha.max():.4f}]")
    chi_variation = float(bssn.chi.max() - bssn.chi.min())
    print(f"    chi variation across grid: {chi_variation:.4f}  "
          f"(non-trivial curvature)")

    # Wrap in Metric interface.
    metric = BSSNGriddedMetric(bssn, L=L)

    # Sanity-check: metric at box centre vs. far corner.
    g_centre = metric.g(np.array([0.0, L/2, L/2, L/2]))
    g_far    = metric.g(np.array([0.0, 0.5*dh, 0.5*dh, 0.5*dh]))
    print(f"  Sanity: g_tt at centre = {g_centre[0,0]:.4f}, "
          f"g_tt at corner = {g_far[0,0]:.4f}")
    print(f"          g_xx at centre = {g_centre[1,1]:.4f}, "
          f"g_xx at corner = {g_far[1,1]:.4f}")

    # ----------------------------------------------------------------
    # Launch null geodesics at varying impact parameters.
    # ----------------------------------------------------------------
    # Launch from the +x edge moving in -x direction with offset y = b.
    x_launch = L - 4 * dh
    impact_parameters = [0.05 * L, 0.10 * L, 0.15 * L, 0.20 * L, 0.25 * L,
                         0.30 * L, 0.40 * L]

    # Direction: -x (toward the matter core at box centre)
    direction = np.array([-1.0, 0.0, 0.0])

    # Tighter integrator timestep since the metric varies on grid scale dh.
    n_steps = 4000 if HIGH_RES else 2000
    dt_step = dh / 4.0   # photon traverses 4 cells per step ish (well-resolved)
    evolver = GeodesicEvolver(
        metric=metric, dt=dt_step, fd_step=dh, enforce_normalisation=False,
    )

    classifications = []
    trajectories = []
    null_drifts = []
    chi_min_along_path = []

    # The "passed-through-core" region: chi at least 60% of the way down
    # from chi_max toward chi_min.  In strong-field PSFT (paper Section
    # 7.4) this would be the literal trapped region; here at moderate
    # field it identifies the photon trajectories that pass through the
    # high-curvature interior of the matter source -- the precursor to
    # full trapping.
    chi_edge = float(bssn.chi.min() + 0.6 * (bssn.chi.max() - bssn.chi.min()))
    print()
    print(f"  Tracing null geodesics (n_steps = {n_steps}, dt = {dt_step:.4f})")
    print(f"  'Core-traverse' criterion: photon path reaches "
          f"chi < {chi_edge:.4f}")
    print(f"  (in strong-field PSFT this becomes literal capture; at the")
    print(f"   moderate compactness here, it identifies gravitational")
    print(f"   focussing toward the matter core)")
    print()

    for b in impact_parameters:
        x0 = np.array([0.0, x_launch, L/2 + b, L/2])
        u0 = null_initial_velocity(metric, x0, direction)
        state = GeodesicState(tau=0.0, x=x0, u=u0)
        # Null check at start
        null0 = float(np.einsum('ab,a,b->', metric.g(x0), u0, u0))

        traj = [state.x.copy()]
        chi_min = float('inf')

        for _ in range(n_steps):
            try:
                state = evolver.step(state)
            except (np.linalg.LinAlgError, ValueError):
                break
            traj.append(state.x.copy())
            # Local chi at the photon's current position
            chi_here = metric._trilinear(bssn.chi, state.x[1], state.x[2], state.x[3])
            chi_min = min(chi_min, chi_here)
            # Stop if photon left the box (escaped)
            if (state.x[1] < 2*dh or state.x[1] > L - 2*dh
                    or state.x[2] < 2*dh or state.x[2] > L - 2*dh
                    or state.x[3] < 2*dh or state.x[3] > L - 2*dh):
                break
        traj = np.array(traj)
        # Classification
        if chi_min < chi_edge:
            cls = 'core_traverse'  # passed through the high-curvature interior
        else:
            cls = 'no_core_pass'   # stayed in low-curvature periphery
        classifications.append(cls)
        trajectories.append((b, traj))
        chi_min_along_path.append(chi_min)
        null_final = float(np.einsum('ab,a,b->', metric.g(state.x), state.u, state.u))
        null_drifts.append(abs(null_final))
        print(f"  b = {b:.3f} L : {cls:10s}  chi_min along path = {chi_min:.4f}  "
              f"|null|_final = {abs(null_final):.2e}  ({len(traj)} steps)")

    # Pass criteria.
    pass_lichnerowicz = chi_variation > 0.01      # non-trivial matter-sourced curvature
    pass_small_b = classifications[0] == 'core_traverse'
    pass_large_b = classifications[-1] == 'no_core_pass'
    pass_null    = max(null_drifts) < 1.0
    captured_bs = [b for b, c in zip(impact_parameters, classifications) if c == 'core_traverse']
    escaped_bs  = [b for b, c in zip(impact_parameters, classifications) if c == 'no_core_pass']
    pass_transition = bool(captured_bs and escaped_bs)

    print()
    print(f"  PASS criteria:")
    print(f"    Lichnerowicz solve: chi varies > 0.01           : "
          f"{'PASS' if pass_lichnerowicz else 'FAIL'}")
    print(f"    small-b photons traverse the core               : "
          f"{'PASS' if pass_small_b else 'FAIL'}")
    print(f"    large-b photons stay in the periphery           : "
          f"{'PASS' if pass_large_b else 'FAIL'}")
    print(f"    core-traverse / no-core-pass transition exists  : "
          f"{'PASS' if pass_transition else 'FAIL'}")
    print(f"    null condition |u . u| < 1                      : "
          f"{'PASS' if pass_null else 'FAIL'}")

    # ----------------------------------------------------------------
    # Plot
    # ----------------------------------------------------------------
    fig, axes = plt.subplots(1, 2, figsize=(13, 6))

    # Left: trajectories in (x, y) plane, with chi(x, y, L/2) heatmap
    ax = axes[0]
    chi_slice = bssn.chi[:, :, N//2].T
    im = ax.imshow(chi_slice, origin='lower', extent=[0, L, 0, L],
                   cmap='magma_r', alpha=0.7)
    cbar = plt.colorbar(im, ax=ax, fraction=0.046)
    cbar.set_label('chi (smaller = stronger curvature)')
    color_map = {'core_traverse': 'tab:red', 'no_core_pass': 'tab:green'}
    for (b, traj), cls in zip(trajectories, classifications):
        ax.plot(traj[:, 1], traj[:, 2], '-',
                color=color_map[cls], alpha=0.9, linewidth=1.5,
                label=f'b={b:.2f}L ({cls})')
    # Mark the capture-threshold contour
    contour = ax.contour(np.linspace(0.5*dh, L-0.5*dh, N),
                         np.linspace(0.5*dh, L-0.5*dh, N),
                         chi_slice, levels=[chi_edge],
                         colors='black', linewidths=1, linestyles=':')
    ax.set_xlabel('x'); ax.set_ylabel('y')
    ax.set_title('Photon trajectories on self-gravitating metric\n'
                 '(black dotted: capture-threshold chi contour)')
    ax.legend(loc='upper right', fontsize=6)
    ax.set_aspect('equal')

    # Right: chi profile along central x-axis
    ax = axes[1]
    chi_central = bssn.chi[:, N//2, N//2]
    alpha_central = bssn.alpha[:, N//2, N//2]
    ax.plot(x, chi_central, 'o-', label='chi(x, L/2, L/2)')
    ax.plot(x, alpha_central, 's-', label='alpha(x, L/2, L/2)')
    ax.axhline(chi_edge, color='k', linestyle=':', alpha=0.5,
               label=f'chi capture threshold = {chi_edge:.3f}')
    ax.set_xlabel('x')
    ax.set_ylabel('field value')
    ax.set_title('Lichnerowicz-solved chi and alpha profiles')
    ax.legend(fontsize=8)
    ax.grid(True, alpha=0.3)

    fig.tight_layout()
    out = os.path.join(os.path.dirname(HERE), 'examples', 'out_geon_geodesics.png')
    fig.savefig(out, dpi=120)
    plt.close(fig)
    print(f"\n  Plot saved to {out}")

